return {
	s('mk', {
		t({
			'.PHONY: all build test run clean',
			'',
			'TARGET := ',
		}),
		i(1, 'app'),
		t({
			'',
			'BUILD_COMMAND := ',
		}),
		i(2),
		t({
			'',
			'TEST_COMMAND := ',
		}),
		i(3),
		t({
			'',
			'RUN_COMMAND := ',
		}),
		i(4),
		t({
			'',
			'',
			'all: build',
			'',
			'build:',
			'	$(BUILD_COMMAND)',
			'',
			'test:',
			'	$(TEST_COMMAND)',
			'',
			'run:',
			'	$(RUN_COMMAND)',
			'',
			'clean:',
			'	$(RM) $(TARGET)',
			'',
		}),
		i(0),
	}),

	s('mkcpp', {
		t({
			'.PHONY: all build test run clean',
			'',
			'TARGET := ',
		}),
		i(1, 'main'),
		t({
			'',
			'BUILD_COMMAND := ',
		}),
		i(2, 'g++ -std=c++17 -Wall -Wextra -o $(TARGET) *.cpp'),
		t({
			'',
			'TEST_COMMAND := ',
		}),
		i(3, './$(TARGET) --test'),
		t({
			'',
			'RUN_COMMAND := ',
		}),
		i(4, './$(TARGET)'),
		t({
			'',
			'',
			'all: build',
			'',
			'build:',
			'	$(BUILD_COMMAND)',
			'',
			'test:',
			'	$(TEST_COMMAND)',
			'',
			'run:',
			'	$(RUN_COMMAND)',
			'',
			'clean:',
			'	$(RM) $(TARGET)',
			'',
		}),
		i(0),
	}),

	s('mkcpp-adv', {
		t({
			'.PHONY: all build test run debug clean',
			'.DEFAULT_GOAL := all',
			'',
			'TARGET := ',
		}),
		i(1, 'main'),
		t({
			'',
			'SRCS := $(wildcard *.cpp)',
			'OBJS := $(SRCS:.cpp=.o)',
			'DEPS := $(OBJS:.o=.d)',
			'',
			'CXX      ?= g++',
			'CXXFLAGS := ',
		}),
		i(2, '-std=c++17 -Wall -Wextra'),
		t({
			'',
			'LDFLAGS  :=',
			'',
			'all: build',
			'',
			'build: $(TARGET)',
			'',
			'$(TARGET): $(OBJS)',
			'	$(CXX) $(CXXFLAGS) $(LDFLAGS) -o $@ $^',
			'',
			'%.o: %.cpp',
			'	$(CXX) $(CXXFLAGS) -MMD -MP -c $< -o $@',
			'',
			'test: build',
			'	./$(TARGET) --test',
			'',
			'run: build',
			'	./$(TARGET)',
			'',
			'debug: CXXFLAGS += -DDEBUG -g -O0',
			'debug: clean build',
			'',
			'clean:',
			'	$(RM) $(TARGET) $(OBJS) $(DEPS)',
			'',
			'-include $(DEPS)',
			'',
		}),
		i(0),
	}),
}
