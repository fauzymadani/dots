return {
	s('cmk', {
		t({
			'# Usage:',
			'#   cmake -B build -DCMAKE_BUILD_TYPE=Release',
			'#   cmake --build build',
			'#   ctest --test-dir build --output-on-failure',
			'',
			'cmake_minimum_required(VERSION 3.20)',
			'project(',
		}),
		i(1, 'app'),
		t({
			' LANGUAGES CXX)',
			'',
			'set(CMAKE_CXX_STANDARD 17)',
			'set(CMAKE_CXX_STANDARD_REQUIRED ON)',
			'',
		}),
		i(2, 'add_executable(app src/main.cpp)'),
		t({
			'',
		}),
		i(3, 'enable_testing()'),
		t({
			'',
		}),
		i(0),
	}),

	s('cmkcpp', {
		t({
			'# Usage:',
			'#   cmake -B build',
			'#   cmake --build build',
			'#   ./build/${PROJECT_NAME} --test',
			'',
			'cmake_minimum_required(VERSION 3.20)',
			'project(',
		}),
		i(1, 'main'),
		t({
			' LANGUAGES CXX)',
			'',
			'set(CMAKE_CXX_STANDARD 17)',
			'set(CMAKE_CXX_STANDARD_REQUIRED ON)',
			'',
			'add_executable(${PROJECT_NAME} ',
		}),
		i(2, 'main.cpp'),
		t({
			')',
			'',
			'target_compile_options(${PROJECT_NAME} PRIVATE ',
		}),
		i(3, '-Wall -Wextra'),
		t({
			')',
			'',
		}),
		i(0),
	}),

	s('cmkcpp-adv', {
		t({
			'# Usage:',
			'#   cmake -B build -DCMAKE_BUILD_TYPE=Release && cmake --build build',
			'#   cmake -B build-debug -DCMAKE_BUILD_TYPE=Debug && cmake --build build-debug',
			'#   ./build/${PROJECT_NAME} --test',
			'',
			'cmake_minimum_required(VERSION 3.20)',
			'project(',
		}),
		i(1, 'main'),
		t({
			' LANGUAGES CXX)',
			'',
			'set(CMAKE_CXX_STANDARD ',
		}),
		i(2, '17'),
		t({
			')',
			'set(CMAKE_CXX_STANDARD_REQUIRED ON)',
			'set(CMAKE_EXPORT_COMPILE_COMMANDS ON)',
			'',
			'add_executable(${PROJECT_NAME} ',
		}),
		i(3, 'main.cpp'),
		t({
			')',
			'',
			'target_compile_options(${PROJECT_NAME} PRIVATE ',
		}),
		i(4, '-Wall -Wextra'),
		t({
			')',
			'',
			'target_compile_definitions(${PROJECT_NAME} PRIVATE $<$<CONFIG:Debug>:DEBUG>)',
			'target_compile_options(${PROJECT_NAME} PRIVATE $<$<CONFIG:Debug>:-g -O0>)',
			'',
		}),
		i(0),
	}),

	s('cmkcpp-adv-portable', {
		t({
			'# Usage:',
			'#   cmake -B build -DCMAKE_BUILD_TYPE=Release && cmake --build build',
			'#   cmake -B build-debug -DCMAKE_BUILD_TYPE=Debug && cmake --build build-debug',
			'#   ./build/${PROJECT_NAME} --test',
			'',
			'cmake_minimum_required(VERSION 3.20)',
			'project(',
		}),
		i(1, 'main'),
		t({
			' LANGUAGES CXX)',
			'',
			'set(CMAKE_CXX_STANDARD ',
		}),
		i(2, '17'),
		t({
			')',
			'set(CMAKE_CXX_STANDARD_REQUIRED ON)',
			'set(CMAKE_CXX_EXTENSIONS OFF)',
			'set(CMAKE_EXPORT_COMPILE_COMMANDS ON)',
			'',
			'add_executable(${PROJECT_NAME} ',
		}),
		i(3, 'main.cpp'),
		t({
			')',
			'',
			'# MSVC: /W4   GCC/Clang/AppleClang: -Wall -Wextra',
			'target_compile_options(${PROJECT_NAME} PRIVATE',
			'    $<$<CXX_COMPILER_ID:GNU,Clang,AppleClang>:',
		}),
		i(4, '-Wall -Wextra'),
		t({
			'>',
			'    $<$<CXX_COMPILER_ID:MSVC>:/W4>',
			')',
			'',
			'target_compile_definitions(${PROJECT_NAME} PRIVATE $<$<CONFIG:Debug>:DEBUG>)',
			'',
		}),
		i(0),
	}),
}
